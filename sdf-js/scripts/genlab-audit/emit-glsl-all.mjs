// =============================================================================
// WP1-GPU Phase B validation — run the 2D emitter over all 359 audit modules.
// -----------------------------------------------------------------------------
// Per layer: attempt compileSDF2ToGLSL. Outputs:
//   1. stats: layer-level + piece-level success (target ≈ audit's 92% / 95%)
//   2. failure-reason histogram (should be only no-AST / 3D prims / rare ops)
//   3. out/_audit/glsl-bundle.js — window.GLSL_LIB + window.GLSL_CASES for the
//      real-GPU compile test page (compile-test.html). Library emitted once;
//      cases carry the body only.
// Usage: node scripts/genlab-audit/emit-glsl-all.mjs
// =============================================================================

import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { compileSDF2ToGLSL } from '../../src/sdf/sdf2.compile.js';
import { SDF2_GLSL } from '../../src/sdf/sdf3.glsl.js';

const here = dirname(fileURLToPath(import.meta.url));
const auditDir = join(here, '../../examples/genlab/out/_audit');

const files = readdirSync(auditDir).filter((f) => f.endsWith('.mjs'));
const stats = {
  pieces: 0,
  piecesAll: 0,
  piecesSome: 0,
  piecesNone: 0,
  layers: 0,
  layersOK: 0,
  failReasons: new Map(),
};
const cases = [];
const failSamples = [];

for (const file of files.sort()) {
  const id = file.replace(/\.mjs$/, '');
  let mod;
  try {
    mod = await import(join(auditDir, file));
  } catch (e) {
    stats.failReasons.set('module load', (stats.failReasons.get('module load') ?? 0) + 1);
    continue;
  }
  const layers = mod.__layers ?? [];
  stats.pieces += 1;
  let ok = 0;
  layers.forEach((layer, i) => {
    const sdf = layer && (layer.sdf ?? layer);
    stats.layers += 1;
    const r = compileSDF2ToGLSL(sdf, { fnName: 'sdLayer', includeLibrary: false });
    if (r.glsl) {
      ok += 1;
      stats.layersOK += 1;
      cases.push({ id: `${id}#${i}`, body: r.glsl, lines: r.lines });
    } else {
      // normalize reasons for the histogram
      const key = r.error.replace(/'[^']*'/g, "'*'").replace(/\d+/g, 'N');
      stats.failReasons.set(key, (stats.failReasons.get(key) ?? 0) + 1);
      if (failSamples.length < 5) failSamples.push({ id: `${id}#${i}`, error: r.error });
    }
  });
  if (ok === layers.length && layers.length > 0) stats.piecesAll += 1;
  else if (ok > 0) stats.piecesSome += 1;
  else stats.piecesNone += 1;
}

const pctL = ((stats.layersOK / stats.layers) * 100).toFixed(1);
const flowable = stats.piecesAll + stats.piecesSome;
const pctP = ((flowable / stats.pieces) * 100).toFixed(1);
console.log('═══ Phase B 发射结果 ═══');
console.log(
  `件: ${stats.pieces}  全层可发射: ${stats.piecesAll}  部分: ${stats.piecesSome}  零层: ${stats.piecesNone}`,
);
console.log(
  `≥1 层可流光: ${flowable} (${pctP}%)  · 层级: ${stats.layersOK}/${stats.layers} (${pctL}%)`,
);
console.log('── 失败原因:');
for (const [k, v] of [...stats.failReasons.entries()].sort((a, b) => b[1] - a[1])) {
  console.log(`  ${String(v).padStart(5)}  ${k}`);
}
if (failSamples.length) {
  console.log('── 失败样例:');
  for (const s of failSamples) console.log(`  ${s.id}: ${s.error}`);
}
const maxCase = cases.reduce((a, c) => (c.lines > a.lines ? c : a), { lines: 0 });
console.log(`── 最大发射体: ${maxCase.id} (${maxCase.lines} 行)`);

// GPU compile-test bundle. Extras (per-corner round box) live in the emitter;
// re-request one compile WITH library to capture the exact library text.
const libProbe = `${SDF2_GLSL}\n`;
const extras = (await import('../../src/sdf/sdf2.compile.js')).compileSDF2ToGLSL;
// simplest: rebuild library the same way the emitter does — compile a trivial
// sdf with includeLibrary and strip the body.
import('../../src/index.js').then(({ circle }) => {
  const full = extras(circle(1), { fnName: '__probe' });
  const lib = full.glsl.slice(0, full.glsl.indexOf('float __probe'));
  const bundle = [
    '// AUTO-GENERATED by emit-glsl-all.mjs — GPU compile-test input',
    `window.GLSL_LIB = ${JSON.stringify(lib)};`,
    `window.GLSL_CASES = ${JSON.stringify(cases)};`,
    '',
  ].join('\n');
  writeFileSync(join(auditDir, 'glsl-bundle.js'), bundle);
  console.log(
    `── bundle: ${cases.length} cases → out/_audit/glsl-bundle.js (${(bundle.length / 1e6).toFixed(1)} MB)`,
  );
});
